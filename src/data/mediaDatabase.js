export function getRecommendations(watchedMovies, watchedShows) {
  const allWatched = [...watchedMovies, ...watchedShows]

  if (allWatched.length === 0) return { movies: [], shows: [] }

  // Build preference profile: average rating per genre/category
  const categoryRatings = {}
  allWatched.forEach(item => {
    ;(item.categories || []).forEach(cat => {
      if (!categoryRatings[cat]) categoryRatings[cat] = []
      categoryRatings[cat].push(item.rating)
    })
  })

  const categoryAvg = {}
  Object.entries(categoryRatings).forEach(([cat, ratings]) => {
    categoryAvg[cat] = ratings.reduce((a, b) => a + b, 0) / ratings.length
  })

  const watchedTitles = new Set(allWatched.map(i => i.title.toLowerCase().trim()))

  function scoreItem(item) {
    const matchingGenres = item.genres.filter(g => categoryAvg[g] !== undefined)
    if (matchingGenres.length === 0) return null

    const score = matchingGenres.reduce((total, g) => total + categoryAvg[g], 0) / matchingGenres.length
    const topMatches = matchingGenres
      .sort((a, b) => (categoryAvg[b] || 0) - (categoryAvg[a] || 0))
      .slice(0, 2)

    return { ...item, score: Math.round(score * 10) / 10, matchReasons: topMatches }
  }

  const unseenMovies = MOVIE_DATABASE
    .filter(m => !watchedTitles.has(m.title.toLowerCase().trim()))
    .map(scoreItem)
    .filter(Boolean)
    .sort((a, b) => b.score - a.score)

  const unseenShows = SHOW_DATABASE
    .filter(s => !watchedTitles.has(s.title.toLowerCase().trim()))
    .map(scoreItem)
    .filter(Boolean)
    .sort((a, b) => b.score - a.score)

  return { movies: unseenMovies, shows: unseenShows }
}
